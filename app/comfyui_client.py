def _bump(key: str, delta=1) -> None:
    """安全累加统计项（统计失败绝不影响业务）"""
    try:
        _CALL_STATS[key] = _CALL_STATS.get(key, 0) + delta
    except Exception:  # noqa: BLE001
        pass

