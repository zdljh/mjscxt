    @classmethod
    def clean_conflict_negative_tokens(cls, api_prompt: dict) -> dict:
        """从负向提示词槽位剔除与正向 3D 风格冲突的词（P0：风格冲突）

        只处理判定为负向的槽位（含 NEGATIVE_HINTS 之一），不改正向提示词。
        返回 {节点id: 变更说明} 便于审计。
        """
        changed: dict = {}
        for nid, node in (api_prompt or {}).items():
            if not isinstance(node, dict):
                continue
            if str(node.get("class_type") or "") not in ("CLIPTextEncode", "TextEncodeQwenImageEditPlus"):
                continue
            inputs = node.get("inputs") or {}
            for field in PROMPT_TEXT_FIELDS:
                value = inputs.get(field)
                if not isinstance(value, str) or not value.strip():
                    continue
                low = value.lower()
                if not any(h.lower() in low for h in NEGATIVE_HINTS):
                    continue    # 正向槽位不动
                new = value
                removed: List[str] = []
                for tok in CONFLICT_NEGATIVE_SORTED:
                    if tok in new:
                        new = new.replace(tok, "")
                        removed.append(tok)
                if not removed:
                    continue
                new = re.sub(r"[，,、]\s*(?=[，,、])", "", new)
                new = re.sub(r"^\s*[，,、]+\s*", "", new)
                new = re.sub(r"[，,、\s]+$", "", new)
                inputs[field] = new
                changed[str(nid)] = f"{field}: 移除冲突负向词 {removed}"
        if changed:
            logger.info(f"[风格冲突清理] 负向提示词已修正 {len(changed)} 处: {changed}")
        return changed

    @classmethod
    def sanitize_scene_prompt(cls, prompt_zh: str) -> str:
        """场景提示词去人物（P0：场景资产带人）

        场景定义常写「村民三两结伴」→ 资产图实测渲染出 4 人。这里按分句粒度丢弃含人物
        描述的短句，并追加空场景声明；若清洗后为空则回退原文（避免把场景描述清空）。
        """
        text = (prompt_zh or "").strip()
        if not text:
            return text
        parts = [p.strip() for p in _PROMPT_SPLIT_RE.split(text)]
        kept: List[str] = []
        dropped: List[str] = []
        for p in parts:
            if not p:
                continue
            hit = any(w in p for w in CHARACTER_WORDS) or bool(CHARACTER_QTY_RE.search(p))
            if hit:
                dropped.append(p)
            else:
                kept.append(p)
        cleaned = "，".join(kept).strip()
        if not cleaned:
            cleaned = text      # 全句含人物时不至于清空，仅靠正向声明压制
        if dropped:
            logger.info(f"[场景去人] 丢弃人物描述句 {dropped}；清洗后场景描述: {cleaned[:80]}")
        return cleaned.rstrip("。;； ") + SCENE_NO_CHARACTER_SUFFIX

    @staticmethod
    def _harden_no_watermark(api_prompt: dict) -> dict:
        """C 项⑧：图片生成链路彻底去水印（仅改内存中的 API prompt，不动工作流文件）

        对每个提示词节点（CLIPTextEncode / TextEncodeQwenImageEditPlus）：
        - 该槽位是负向提示词 → 追加水印类排除词；
        - 该槽位是正向提示词 → 追加「画面干净、无任何水印/文字」声明。
        幂等：已包含则不重复追加。
        返回 {节点id: 变更说明} 便于日志审计。
        """
        changed = {}
        for nid, node in (api_prompt or {}).items():
            if not isinstance(node, dict):
                continue
            ctype = str(node.get("class_type") or "")
            if ctype not in ("CLIPTextEncode", "TextEncodeQwenImageEditPlus"):
                continue
            inputs = node.get("inputs") or {}
            for field in PROMPT_TEXT_FIELDS:
                value = inputs.get(field)
                if not isinstance(value, str) or not value.strip():
                    continue
                # 幂等：已加固过的槽位直接跳过（否则正向后缀里的"水印"二字会被误判为负向）
                if NO_WATERMARK_POSITIVE_SUFFIX in value or NO_WATERMARK_NEGATIVE_EXTRA in value:
                    continue
                low = value.lower()
                is_negative = any(h.lower() in low for h in NEGATIVE_HINTS)
                if is_negative:
                    if NO_WATERMARK_NEGATIVE_EXTRA in value:
                        continue
                    inputs[field] = value.rstrip("，,;； ") + ", " + NO_WATERMARK_NEGATIVE_EXTRA
                    changed[str(nid)] = f"{field}: 负向追加水印排除词"
                else:
                    if NO_WATERMARK_POSITIVE_SUFFIX in value:
                        continue
                    inputs[field] = value.rstrip("。;； ") + NO_WATERMARK_POSITIVE_SUFFIX
                    changed[str(nid)] = f"{field}: 正向追加无水印声明"
        if changed:
            logger.info(f"[去水印强化] 图片提示词已加固 {len(changed)} 处: {changed}")
        return changed

    @classmethod
    def harden_video_no_text(cls, api_prompt: dict, node_ids=None) -> dict:
        """H3 视频链路：向提示词节点追加「画面内不得出现文字/字幕」声明

        H3 工作流的提示词节点是纯文本节点（Text Multiline），不在图片链路的
        CLIPTextEncode / TextEncodeQwenImageEditPlus 白名单内，故单独处理。
        仅改内存中的 API prompt，不动磁盘工作流文件；幂等（含声明则跳过）。
        """
        changed = {}
        targets = [str(n) for n in (node_ids if node_ids is not None else list(api_prompt or {}))]
        for nid in targets:
            node = (api_prompt or {}).get(str(nid))
            if not isinstance(node, dict):
                continue
            ctype = str(node.get("class_type") or "")
            if ctype not in VIDEO_PROMPT_NODE_TYPES:
                continue
            inputs = node.get("inputs") or {}
            for field in PROMPT_TEXT_FIELDS:
                value = inputs.get(field)
                if not isinstance(value, str) or not value.strip():
                    continue
                if VIDEO_NO_TEXT_SUFFIX in value:
                    continue
                inputs[field] = value.rstrip("。;；\n ") + VIDEO_NO_TEXT_SUFFIX
                changed[str(nid)] = f"{field}: 追加无文字/字幕声明"
        if changed:
            logger.info(f"[H3 无字幕强化] 视频提示词已加固 {len(changed)} 处: {changed}")
        return changed

    def _find_positive_text_node(self, api_prompt: dict, class_types=("CLIPTextEncode",)) -> Optional[str]:
        """在提示词编码节点中定位正向节点（不含负向关键词者）"""
        candidates = []
        for nid, node in api_prompt.items():
            if node.get("class_type") not in class_types:
                continue
            texts = [str(v) for v in (node.get("inputs") or {}).values() if isinstance(v, str)]
            joined = " ".join(texts).lower()
            if not any(h.lower() in joined for h in NEGATIVE_HINTS):
                candidates.append(nid)
        if not candidates:
            # 全部命中负向词时，退化为「id 最大的那个」
            pool = [nid for nid, n in api_prompt.items() if n.get("class_type") in class_types]
            return sorted(pool, key=lambda x: int(x) if str(x).isdigit() else 0)[-1] if pool else None
        # 正向通常有多个文本槽（如 prompt/image1..3），取最后一个可用候选
        return sorted(candidates, key=lambda x: int(x) if str(x).isdigit() else 0)[-1]

    def _generate_base_image(self, workflow_file: str, prompt_zh: str,
                             asset_type: str = None, seed: int = None) -> List[str]:
        """通用基础图生成：更新正向提示词节点

        P0 修复（同轮补充）：
        - asset_type="scene" → 清洗人物描述并追加"空场景"声明（场景资产不得带人）；
        - clean_conflict_negative_tokens 剔除与 3D 正向风格冲突的负向词；
        - seed 用于质检不达标时的重生成（保证与上一版结果不同）。
        """
        api_prompt, meta = self.load_workflow(workflow_file, return_meta=True)
        node_id = self._find_positive_text_node(api_prompt)
        if node_id is None:
            logger.error(f"{workflow_file} 中未找到正向提示词节点，转换元信息: {meta}")
            return []
        # 场景资产去人
        if asset_type == "scene":
            prompt_zh = self.sanitize_scene_prompt(prompt_zh)
        node = api_prompt[node_id]
        if "text" in node["inputs"]:
            node["inputs"]["text"] = prompt_zh
        else:
            # TextEncodeQwenImageEditPlus 等使用 prompt 字段
            for k, v in list(node["inputs"].items()):
                if isinstance(v, str):
                    node["inputs"][k] = prompt_zh
        logger.info(f"[{workflow_file}] 正向提示词节点 {node_id} 已更新（共 {len(api_prompt)} 节点）")
        self.clean_conflict_negative_tokens(api_prompt)                 # P0：清理风格冲突负向词
        if seed is not None:
            logger.info(f"资产采样种子已注入: {self._inject_seed(api_prompt, seed)}")
        self._harden_no_watermark(api_prompt)   # C 项⑧：图片一律去水印

        prompt_id = self.queue_prompt(api_prompt)
        history = self.wait_for_completion(prompt_id)
        return self.get_output_files(history, ".png")

